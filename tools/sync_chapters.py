#!/usr/bin/env python3
"""Keep _quarto.yml's exploration chapters and explorations/_overview.md in sync with registry.yaml.

Explorations with status `obsolete` go under the "Obsolete explorations" part
(markers `# <obsolete>`), all others under "Explorations" (markers `# <explorations>`).
"""
import os, re
import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
reg = yaml.safe_load(open(os.path.join(ROOT, "explorations", "registry.yaml"))) or {}
exps = [e for e in reg.get("explorations") or []
        if os.path.exists(os.path.join(ROOT, "explorations", e["id"], "index.qmd"))]
active = [e for e in exps if e.get("status") != "obsolete"]
obsolete = [e for e in exps if e.get("status") == "obsolete"]
q = open(os.path.join(ROOT, "_quarto.yml")).read()
for tag, group in (("explorations", active), ("obsolete", obsolete)):
    m = re.search(rf"^( *)# <{tag}>.*?\n(.*?)^\1# </{tag}>", q, re.S | re.M)
    if not m:
        raise SystemExit(f"markers '# <{tag}>' / '# </{tag}>' not found in _quarto.yml")
    block = "".join(f"{m.group(1)}- explorations/{e['id']}/index.qmd\n" for e in group)
    if not group and tag == "obsolete":  # a part may not be empty
        block = f"{m.group(1)}- explorations/obsolete-none.qmd\n"
    q = q[: m.start(2)] + block + q[m.end(2):]
open(os.path.join(ROOT, "_quarto.yml"), "w").write(q)


def table(group):
    rows = ["| Exploration | Question | Status | Code |", "|---|---|---|---|"]
    for e in group:
        c = e.get("code") or {}
        commit = f"`{c['commit'][:10]}`" if c.get("commit") else "uncommitted"
        qtext = str(e.get("question", "")).replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")
        rows.append(f"| @sec-{e['id']} | {qtext} | {e.get('status', '')} | `{c.get('branch', '')}` @ {commit} |")
    return "\n".join(rows) + "\n"


out = "<!-- generated by tools/sync_chapters.py; do not edit -->\n\n" + table(active)
if obsolete:
    out += "\nObsolete explorations (approaches that did not work):\n\n" + table(obsolete)
open(os.path.join(ROOT, "explorations", "_overview.md"), "w").write(out)
print(f"{len(active)} exploration chapter(s), {len(obsolete)} obsolete")
