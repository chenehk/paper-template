#!/usr/bin/env python3
"""Keep _quarto.yml's exploration chapters and explorations/_overview.md in sync with registry.yaml.

Explorations with status `obsolete` go under the "Obsolete explorations" part
(markers `# <obsolete>`), all others under "Explorations" (markers `# <explorations>`).

Sections: the registry's top-level `sections` list ({id, title}, in display order) and
each exploration's `section` (one of those ids) group the Explorations part. Quarto books
cannot nest parts, so the chapter list stays flat (ordered by section) and
web/exploration-sections.html tells web/part-links.html how to fold the sidebar.
Explorations without a section come last, ungrouped.
"""
import json, os, re
import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
reg = yaml.safe_load(open(os.path.join(ROOT, "explorations", "registry.yaml"))) or {}
exps = [e for e in reg.get("explorations") or []
        if os.path.exists(os.path.join(ROOT, "explorations", e["id"], "index.qmd"))]
sections = reg.get("sections") or []
order = {s["id"]: i for i, s in enumerate(sections)}
unknown = sorted({e["section"] for e in exps if e.get("section") and e["section"] not in order})
if unknown:
    raise SystemExit(f"section(s) {unknown} not in the registry's `sections` list")
active = [e for e in exps if e.get("status") != "obsolete"]
active.sort(key=lambda e: order.get(e.get("section"), len(sections)))  # stable: registry order within a section
obsolete = [e for e in exps if e.get("status") == "obsolete"]
q = open(os.path.join(ROOT, "_quarto.yml")).read()
for tag, group in (("explorations", active), ("obsolete", obsolete)):
    m = re.search(rf"^( *)# <{tag}>.*?\n(.*?)^\1# </{tag}>", q, re.S | re.M)
    if not m:
        raise SystemExit(f"markers '# <{tag}>' / '# </{tag}>' not found in _quarto.yml")
    block = "".join(f"{m.group(1)}- explorations/{e['id']}/index.qmd\n" for e in group)
    if not group and tag == "obsolete":  # a part may not be empty
        block = f"{m.group(1)}- explorations/obsolete-none.qmd\n"
    q = q[: m.start(2)] + block + q[m.end(2):]
open(os.path.join(ROOT, "_quarto.yml"), "w").write(q)


def table(group):
    rows = ["| Exploration | Question | Status | Code |", "|---|---|---|---|"]
    for e in group:
        c = e.get("code") or {}
        commit = f"`{c['commit'][:10]}`" if c.get("commit") else "uncommitted"
        qtext = str(e.get("question", "")).replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")
        rows.append(f"| @sec-{e['id']} | {qtext} | {e.get('status', '')} | `{c.get('branch', '')}` @ {commit} |")
    return "\n".join(rows) + "\n"


titles = {s["id"]: s["title"] for s in sections}
pages = {f"explorations/{e['id']}/index.html": titles[e["section"]] for e in active if e.get("section")}
with open(os.path.join(ROOT, "web", "exploration-sections.html"), "w") as f:
    f.write("<!-- generated by tools/sync_chapters.py from explorations/registry.yaml; do not edit -->\n<script>\n"
            f"window.EXPLORATION_SECTIONS = {json.dumps({'order': [s['title'] for s in sections], 'pages': pages}, indent=1)};\n"
            "</script>\n")

def fold(title, body, collapsed=False):
    """A collapsible callout: a box with a title in LaTeX, a foldable section in HTML."""
    return (f'::: {{.callout-note collapse="{str(collapsed).lower()}" appearance="simple" icon=false}}\n'
            f"## {title}\n\n{body}:::\n\n")


out = "<!-- generated by tools/sync_chapters.py; do not edit -->\n\n"
groups = [(s["title"], [e for e in active if e.get("section") == s["id"]]) for s in sections]
groups.append(("Other" if sections else None, [e for e in active if not e.get("section")]))
for title, group in groups:
    if not group:
        continue
    out += fold(f"{title} ({len(group)})", table(group)) if title else table(group) + "\n"
if not active:
    out += "No explorations yet.\n\n"
if obsolete:
    out += fold(f"Obsolete explorations ({len(obsolete)})",
                "Approaches that did not work.\n\n" + table(obsolete), collapsed=True)
open(os.path.join(ROOT, "explorations", "_overview.md"), "w").write(out)
print(f"{len(active)} exploration chapter(s) in {len(sections)} section(s), {len(obsolete)} obsolete")
