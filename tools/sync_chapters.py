#!/usr/bin/env python3
"""Keep _quarto.yml's experiment chapters and experiments/_overview.md in sync with registry.yaml."""
import os, re
import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
reg = yaml.safe_load(open(os.path.join(ROOT, "experiments", "registry.yaml"))) or {}
exps = [e for e in reg.get("experiments") or [] if os.path.exists(os.path.join(ROOT, "experiments", e["id"], "index.qmd"))]
q = open(os.path.join(ROOT, "_quarto.yml")).read()
m = re.search(r"^( *)# <experiments>.*?\n(.*?)^\1# </experiments>", q, re.S | re.M)
if not m:
    raise SystemExit("markers '# <experiments>' / '# </experiments>' not found in _quarto.yml")
ind = m.group(1)
block = "".join(f"{ind}- experiments/{e['id']}/index.qmd\n" for e in exps)
q = q[: m.start(2)] + block + q[m.end(2):]
open(os.path.join(ROOT, "_quarto.yml"), "w").write(q)
rows = ["| Experiment | Question | Status | Code |", "|---|---|---|---|"]
for e in exps:
    c = e.get("code") or {}
    commit = f"`{c['commit'][:10]}`" if c.get("commit") else "uncommitted"
    q = str(e.get("question", "")).replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")
    rows.append(f"| @sec-{e['id']} | {q} | {e.get('status', '')} | `{c.get('branch', '')}` @ {commit} |")
open(os.path.join(ROOT, "experiments", "_overview.md"), "w").write(
    "<!-- generated by tools/sync_chapters.py; do not edit -->\n\n" + "\n".join(rows) + "\n")
print(f"{len(exps)} experiment chapter(s)")
