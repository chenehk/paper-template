#!/usr/bin/env python3
"""Generate explorations/<id>/tables/<name>.md from explorations/<id>/results.json.

results.json: {"tables": {name: {"caption", "label", "columns": [...], "rows": [[...]],
"format": optional per-column Python format strings}}, "metrics": {...}, "sources": {...}}.
Tables are written as Quarto pipe tables with a caption and a {#tbl-...} label, so
@tbl-... references work on the site and in LaTeX. Run with no arguments to
regenerate every exploration.
"""
import glob, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def cell(v, fmt):
    if v is None:
        return "–"
    if fmt and isinstance(v, (int, float)):
        return format(v, fmt)
    return str(v).replace("|", "\\|")


def render(t):
    cols, fmts = t["columns"], t.get("format") or [None] * len(t["columns"])
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in t["rows"]:
        out.append("| " + " | ".join(cell(v, f) for v, f in zip(r, fmts)) + " |")
    out.append("")
    out.append(f": {t.get('caption', '')} {{#{t['label']}}}" if t.get("label") else f": {t.get('caption', '')}")
    return "\n".join(out) + "\n"


def build(exp_dir):
    path = os.path.join(exp_dir, "results.json")
    if not os.path.exists(path):
        return 0
    res = json.load(open(path))
    os.makedirs(os.path.join(exp_dir, "tables"), exist_ok=True)
    for name, t in res.get("tables", {}).items():
        with open(os.path.join(exp_dir, "tables", f"{name}.md"), "w") as f:
            f.write("<!-- generated by tools/make_tables.py from results.json; do not edit -->\n\n" + render(t))
    return len(res.get("tables", {}))


if __name__ == "__main__":
    dirs = sys.argv[1:] or sorted(glob.glob(os.path.join(ROOT, "explorations", "exp-*")))
    for d in dirs:
        print(f"{os.path.basename(d)}: {build(d)} table(s)")
